#!/usr/bin/env node
// Copies poetic/browser/poetic.css into a generated TS module so app code
// can import it as a plain string, sidestepping Turbopack's inability to
// place a require.resolve()'d or `?raw`-imported CSS file from a
// node_modules package into the server/client module graph. Runs on every
// `npm install` (see package.json's postinstall) so it stays in sync
// whenever the pinned poetic version bumps.

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

export function syncPoeticCss(requireResolve, readFile, writeFile, scriptDir, packageJsonPath) {
  let cssPath;
  try {
    cssPath = requireResolve("poetic/browser/poetic.css");
  } catch (cause) {
    const packageJson = JSON.parse(readFile(packageJsonPath, "utf8"));
    const pinnedVersion = packageJson.dependencies.poetic;
    throw new Error(
      `Could not resolve poetic/browser/poetic.css from the pinned poetic ` +
        `dependency (${pinnedVersion}). Its browser/poetic.css export path ` +
        `may have moved — check the release notes for the pinned version ` +
        `and update this script's require.resolve() call to match.`,
      { cause },
    );
  }

  const css = readFile(cssPath, "utf8");

  const outPath = path.join(scriptDir, "..", "src", "lib", "poetic-css.generated.ts");

  const contents = `// Generated by scripts/sync-poetic-css.mjs from poetic/browser/poetic.css.
// Do not edit by hand — re-run \`npm install\` to regenerate.
export const poeticCss = ${JSON.stringify(css)};
`;

  writeFile(outPath, contents);
  console.log(`Wrote ${outPath} (${css.length} bytes)`);
}

function main() {
  const require = createRequire(import.meta.url);
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));

  syncPoeticCss(
    require.resolve.bind(require),
    readFileSync,
    writeFileSync,
    scriptDir,
    path.join(scriptDir, "..", "package.json"),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
